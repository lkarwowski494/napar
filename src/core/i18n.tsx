export type Translations = typeof translations.pl;

interface LanguageContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: Translations;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'pl',
  setLanguage: () => {},
  t: translations.pl,
});

function getStoredLanguage(): SupportedLanguage | null {
  try {
    const db = require('./database');
    if (db && typeof db.getAppSetting === 'function') {
      const persisted = db.getAppSetting('app_language', '');
      if (persisted === 'pl' || persisted === 'en') {
        return persisted;
      }
    }
  } catch {
    // fallback
  }
  return null;
}

function persistLanguage(lang: SupportedLanguage): void {
  try {
    const db = require('./database');
    if (db && typeof db.setAppSetting === 'function') {
      db.setAppSetting('app_language', lang);
    }
  } catch {
    // fallback
  }
}

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguage>(() => {
    try {
      const persisted = getStoredLanguage();
      if (persisted === 'pl' || persisted === 'en') {
        return persisted;
      }
    } catch {
      // safe fallback
    }
    return getStoredLanguage() || detectSystemLanguage();
  });

  const setLanguage = (lang: SupportedLanguage) => {
    setLanguageState(lang);
    try {
      persistLanguage(lang);
    } catch {
      // safe fallback
    }
  };

  const value = {
    language,
    setLanguage,
    t: translations[language] || translations.en,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export function useTranslation(): LanguageContextType {
  return useContext(LanguageContext);
}

export function getCurrentTranslations(): Translations {
  try {
    const persisted = getStoredLanguage();
    if (persisted === 'pl' || persisted === 'en') {
      return translations[persisted] || translations.en;
    }
  } catch {
    // fallback
  }
  const lang = detectSystemLanguage();
  return translations[lang] || translations.en;
}

/**
 * Wykrywa kategorię liczby mnogiej zgodnie z regułami CLDR / Intl.PluralRules.
 * Posiada wbudowany bezpieczny fallback dla środowiska Hermes / braku pełnego Intl.
 */
export function getPluralCategory(
  lang: string,
  count: number
): 'zero' | 'one' | 'two' | 'few' | 'many' | 'other' {
  try {
    if (typeof Intl !== 'undefined' && typeof Intl.PluralRules === 'function') {
      return new Intl.PluralRules(lang).select(count) as any;
    }
  } catch {
    // bezpieczny fallback dla Hermesa
  }

  const abs = Math.abs(Math.floor(count));
  if (lang.toLowerCase().startsWith('pl')) {
    const n = abs % 100;
    const n10 = n % 10;
    if (abs === 1) return 'one';
    if (n10 >= 2 && n10 <= 4 && (n < 12 || n > 14)) return 'few';
    return 'many';
  }

  return abs === 1 ? 'one' : 'other';
}

/**
 * Polska odmiana gramatyczna liczebników (RD-ENG-09, NFR-I18N-007).
 * Dla n = |x| mod 100, n10 = n mod 10:
 * - jeśli |x| === 1 -> one (np. 1 seria, 1 sekunda, 1 klik)
 * - jeśli n10 in {2, 3, 4} i n not in {12, 13, 14} -> few (np. 2 serie, 22 serie, 104 serie)
 * - inaczej -> many (np. 0 serii, 5 serii, 12 serii, 21 serii, 112 serii)
 */
export function pluralPl(count: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.floor(count));
  const n = abs % 100;
  const n10 = n % 10;
  if (abs === 1) return one;
  if (n10 >= 2 && n10 <= 4 && (n < 12 || n > 14)) return few;
  return many;
}

/**
 * Uniwersalny helper pluralizacji dla języków aplikacji ('pl' | 'en') oparty o Intl.PluralRules
 */
export function plural(
  lang: SupportedLanguage,
  count: number,
  forms: { one: string; few?: string; many?: string; other?: string; zero?: string; two?: string }
): string {
  const category = getPluralCategory(lang, count);
  if (forms[category]) {
    return forms[category]!;
  }
  if (category === 'few' && forms.many) return forms.many;
  if (category === 'many' && forms.few) return forms.few;
  return forms.other ?? forms.many ?? forms.few ?? forms.one;
}

/**
 * Uniwersalny formatator szablonów z podstawianiem tokenów {param} (wielokrotne wystąpienia)
 */
export function formatTemplate(template: string, params: Record<string, string | number>): string {
  if (!template) return '';
  let result = template;
  for (const [key, value] of Object.entries(params)) {
    result = result.split(`{${key}}`).join(String(value));
  }
  return result;
}
