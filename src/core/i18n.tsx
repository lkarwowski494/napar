export type SupportedLanguage = 'pl' | 'en';

export function detectSystemLanguage(): SupportedLanguage {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale;
    if (locale && locale.toLowerCase().startsWith('pl')) {
      return 'pl';
    }
  } catch {
    // fallback
  }
  return 'en';
}

